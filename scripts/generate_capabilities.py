#!/usr/bin/env python3
"""Generate native contract constants from the shared registry; --check detects drift."""
import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from clients.capabilities import registry


def generate():
    data = registry()
    contracts = {c['name']: c for c in data['contracts']}
    defs = data['$defs']
    prep = contracts['prepare_near_player']
    assembly = contracts['assemble_dish']
    def strings(name, values):
        return '        public static readonly string[] ' + name + ' = { ' + ', '.join(json.dumps(v) for v in values) + ' };'
    lines = [
        '// Generated by scripts/generate_capabilities.py. Edit clients/capabilities.json.',
        'namespace SousChef.Core', '{', '    public static class CapabilityRegistry', '    {',
        f'        public const int Version = {data["version"]};',
        f'        public const string Hash = "{data["registry_hash"]}";',
        f'        public const int MaxRepetitions = {prep["repeat"]["maximum"]};',
        f'        public const int MaxPreparationItems = {prep["parameters"]["properties"]["items"]["maxItems"]};',
        f'        public const int MaxQuantity = {defs["quantity"]["maximum"]};',
        f'        public const int MaxAllocationGroup = {assembly["parameters"]["properties"]["bases"]["maxItems"]};',
        strings('Tasks', (c['name'] for c in contracts.values() if c['kind'] == 'task')),
        strings('Actions', (c['name'] for c in contracts.values() if c['kind'] == 'action' and c['category'] != 'logistics')),
        strings('Logistics', (c['name'] for c in contracts.values() if c.get('category') == 'logistics')),
        strings('Preparations', defs['preparation']['enum']),
        strings('WorkConditions', defs['work_condition']['enum']),
        strings('WaitConditions', defs['wait_condition']['enum']),
        '        public static object Describe()',
        '        { return Json.Object("version", Version, "registryHash", Hash, "tasks", Tasks, "actions", ActionRun.AllNames); }',
        '    }', '}', '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'src/Core/CapabilityRegistry.cs'
    content = generate()
    if args.check:
        if not path.exists() or path.read_text() != content:
            parser.exit(1, 'Native capability constants are stale; run scripts/generate_capabilities.py\n')
    else:
        path.write_text(content)
